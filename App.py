def init_db():
    """Create the portal tables in Supabase automatically if they do not exist."""
    schema = """
    CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL UNIQUE,
        display_name TEXT NOT NULL,
        password_hash TEXT NOT NULL,
        password_salt TEXT NOT NULL,
        role TEXT NOT NULL DEFAULT 'learner' CHECK(role IN ('admin','learner')),
        active BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TEXT NOT NULL
    );
    CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_uq ON users (LOWER(username));
    CREATE TABLE IF NOT EXISTS questions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        body TEXT NOT NULL,
        topic TEXT NOT NULL,
        difficulty TEXT NOT NULL,
        question_date TEXT NOT NULL,
        deadline TEXT,
        link TEXT,
        created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
        created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS progress (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
        status TEXT NOT NULL DEFAULT 'Not Started',
        answer_notes TEXT NOT NULL DEFAULT '',
        updated_at TEXT NOT NULL,
        UNIQUE(user_id, question_id)
    );
    CREATE TABLE IF NOT EXISTS sessions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        topic TEXT NOT NULL,
        session_date TEXT NOT NULL,
        mentor TEXT,
        meeting_link TEXT,
        notes TEXT,
        created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
        created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS announcements (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        message TEXT NOT NULL,
        created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
        created_at TEXT NOT NULL
    );
    """
    with db() as conn:
        conn.executescript(schema)


def now_iso():
    return datetime.now().isoformat(timespec="seconds")


def password_parts(password: str, salt_hex: str | None = None):
    salt = bytes.fromhex(salt_hex) if salt_hex else secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, 310_000)
    return digest.hex(), salt.hex()


def verify_password(password, salt_hex, expected_hash):
    actual_hash, _ = password_parts(password, salt_hex)
    return hmac.compare_digest(actual_hash, expected_hash)


def user_count():
    with db() as conn:
        return conn.execute("SELECT COUNT(*) FROM users").fetchone()[0]


def get_user_by_username(username):
    with db() as conn:
        return conn.execute(
            "SELECT * FROM users WHERE LOWER(username) = LOWER(?)", (username.strip(),)
        ).fetchone()


def create_user(username, display_name, password, role="learner"):
    username = username.strip()
    display_name = display_name.strip()
    if len(username) < 3:
        raise ValueError("Username must contain at least 3 characters.")
    if len(password) < 10:
        raise ValueError("Password must contain at least 10 characters.")
    if not display_name:
        raise ValueError("Please enter a display name.")
    password_hash, salt = password_parts(password)
    with db() as conn:
        conn.execute(
            """INSERT INTO users(username, display_name, password_hash, password_salt, role, active, created_at)
               VALUES (?, ?, ?, ?, ?, TRUE, ?)""",
            (username, display_name, password_hash, salt, role, now_iso()),
        )
        conn.commit()


