class HybridRow(dict):
    """Dictionary row that also supports legacy row[0] access."""
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def hybrid_row_factory(cursor):
    # Some statements (for example CREATE TABLE) return no result columns.
    # In that case, use psycopg's tuple row factory instead of reading
    # cursor.description, which is None for statements without a result set.
    if cursor.description is None:
        return tuple_row(cursor)

    columns = [column.name for column in cursor.description]
    return lambda values: HybridRow(zip(columns, values))


class CompatConnection:
    """Small compatibility layer for the starter app's SQLite-style calls."""
    def __init__(self, connection):
        self._connection = connection

    def execute(self, sql, params=()):
        # The app's SQL uses ? placeholders; translate them to psycopg placeholders.
        return self._connection.execute(sql.replace("?", "%s"), params)

    def executescript(self, script):
        # Used only for our trusted, static schema statements at startup.
        for statement in script.split(";"):
            if statement.strip():
                self._connection.execute(statement)

    def commit(self):
        self._connection.commit()

    def rollback(self):
        self._connection.rollback()


@contextmanager
def db():
    database_url = get_database_url()
    if not database_url:
        raise RuntimeError(
            "Supabase database connection is not configured. Add SUPABASE_DB_URL "
            "to .streamlit/secrets.toml locally or Streamlit Cloud app Secrets."
        )
    connection = psycopg.connect(
        database_url,
        sslmode="require",
        connect_timeout=10,
        row_factory=hybrid_row_factory,
    )
    compat = CompatConnection(connection)
    try:
        yield compat
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()

